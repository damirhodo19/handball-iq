/** Apply shared HR MT fixes (and optional extra patterns). */
export function applyHrMtFixes(text, extra = []) {
  if (!text || typeof text !== 'string') return text;
  let out = text;
  for (const [re, rep] of [...HR_MT_FIXES, ...extra]) out = out.replace(re, rep);
  return out;
}
