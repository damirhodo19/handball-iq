function plannerPack(
  slug: string,
  en: { m1: string; m1o: string; m1i: string; m1c: string; m2: string; m2o: string; m2i: string; m2c: string; g: string; go: string; gi: string; gc: string },
  hr: typeof en,
  de: typeof en,
): { en: Dict; hr: Dict; de: Dict } {
  const map = (lang: typeof en) => ({
    [`planner.block.${slug}.main1`]: lang.m1,
    [`planner.obj.${slug}.main1`]: lang.m1o,
    [`planner.ins.${slug}.main1`]: lang.m1i,
    [`planner.cp.${slug}.main1`]: lang.m1c,
    [`planner.block.${slug}.main2`]: lang.m2,
    [`planner.obj.${slug}.main2`]: lang.m2o,
    [`planner.ins.${slug}.main2`]: lang.m2i,
    [`planner.cp.${slug}.main2`]: lang.m2c,
    [`planner.block.${slug}.game`]: lang.g,
    [`planner.obj.${slug}.game`]: lang.go,
    [`planner.ins.${slug}.game`]: lang.gi,
    [`planner.cp.${slug}.game`]: lang.gc,
  });
  return { en: map(en), hr: map(hr), de: map(de) };
}

